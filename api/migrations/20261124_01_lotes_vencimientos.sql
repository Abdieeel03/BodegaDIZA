-- Migración autorizada exclusivamente para la base académica bodega_diza_test.
-- No ejecutar automáticamente al arrancar. Ensayar primero en una copia aislada.
-- No actualiza fechas, cantidades, tickets ni movimientos existentes.
BEGIN;
DO $$ BEGIN
    IF current_database() <> 'bodega_diza_test' THEN
        RAISE EXCEPTION 'Esta migración requiere la base bodega_diza_test';
    END IF;
END $$;

ALTER TABLE public.productos
    ADD COLUMN permite_sin_vencimiento boolean NOT NULL DEFAULT false,
    ADD COLUMN justificacion_sin_vencimiento varchar(500);

ALTER TABLE public.lotes_producto
    ALTER COLUMN fecha_vencimiento DROP NOT NULL,
    ADD COLUMN precision_vencimiento varchar(20),
    ADD COLUMN mes_vencimiento varchar(7),
    ADD COLUMN version bigint NOT NULL DEFAULT 0;

-- NULL en precisión identifica exclusivamente los datos históricos conservados.
ALTER TABLE public.lotes_producto ADD CONSTRAINT ck_lote_vencimiento_hibrido CHECK (
    (precision_vencimiento IS NULL AND mes_vencimiento IS NULL)
    OR (precision_vencimiento = 'EXACTA' AND fecha_vencimiento IS NOT NULL AND mes_vencimiento IS NULL)
    OR (precision_vencimiento = 'MES_ANIO' AND fecha_vencimiento IS NULL
        AND mes_vencimiento IS NOT NULL AND mes_vencimiento ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
    OR (precision_vencimiento IN ('PENDIENTE', 'NO_APLICA') AND fecha_vencimiento IS NULL AND mes_vencimiento IS NULL)
) NOT VALID;

CREATE TABLE public.regularizaciones_lote (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id bigint NOT NULL REFERENCES public.productos(id),
    lote_origen_id bigint REFERENCES public.lotes_producto(id),
    lote_destino_id bigint REFERENCES public.lotes_producto(id),
    usuario_id bigint NOT NULL REFERENCES public.usuarios(id),
    fecha timestamp NOT NULL,
    accion varchar(20) NOT NULL,
    cantidad numeric(12,3) NOT NULL CHECK (cantidad >= 0),
    antes varchar(1000) NOT NULL,
    despues varchar(1000) NOT NULL,
    motivo varchar(500) NOT NULL
);
CREATE INDEX idx_regularizacion_origen ON public.regularizaciones_lote(lote_origen_id);
CREATE INDEX idx_regularizacion_destino ON public.regularizaciones_lote(lote_destino_id);
CREATE INDEX idx_regularizacion_producto ON public.regularizaciones_lote(producto_id);

COMMIT;
